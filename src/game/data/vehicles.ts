export function plateGen() {
  const L = "ABCDEFGHJKLMNPRSTUVWXYZ";
  const pick = (s: string) => s[Math.floor(Math.random() * s.length)];
  return `NC ${pick(L)}${pick(L)} ${Math.floor(100 + Math.random() * 899)}`;
}
